import React, { useState } from 'react';
import type { Recipe, UserIngredient, IngredientItem } from '../types/recipe';
import { isIngredientMatched } from '../utils/normalizer';
import {
  X,
  Heart,
  CheckCircle,
  Copy,
  Users,
  Check,
  AlertCircle,
  PartyPopper,
} from 'lucide-react';
import confetti from 'canvas-confetti';
import { RecipeImage } from './RecipeImage';

interface RecipeDetailModalProps {
  recipe: Recipe;
  userIngredients: UserIngredient[];
  isFavorite: boolean;
  isCooked: boolean;
  onToggleFavorite: (recipeId: string) => void;
  onMarkCooked: (recipeId: string) => void;
  onClose: () => void;
}

export const RecipeDetailModal: React.FC<RecipeDetailModalProps> = ({
  recipe,
  userIngredients,
  isFavorite,
  isCooked,
  onToggleFavorite,
  onMarkCooked,
  onClose,
}) => {
  const [servings, setServings] = useState<number>(recipe.baseServings);
  const [copiedShoppingList, setCopiedShoppingList] = useState(false);
  const [checkedSteps, setCheckedSteps] = useState<number[]>([]);

  const userNormalizedList = userIngredients.map((i) => i.normalizedName);

  // Compute missing ingredients
  const missingItems: IngredientItem[] = recipe.ingredients.filter(
    (ing) => !ing.optional && !isIngredientMatched(ing.normalizedName, userNormalizedList)
  );

  // Calculate scaled quantity
  const scaleMultiplier = servings / recipe.baseServings;

  const formatScaledAmount = (amount: number): string => {
    const scaled = amount * scaleMultiplier;
    // Format to 2 decimal places if fractional, otherwise integer
    if (Number.isInteger(scaled)) return scaled.toString();
    if (scaled < 1) {
      if (Math.abs(scaled - 0.5) < 0.05) return '1/2';
      if (Math.abs(scaled - 0.25) < 0.05) return '1/4';
      if (Math.abs(scaled - 0.75) < 0.05) return '3/4';
      if (Math.abs(scaled - 0.33) < 0.05) return '1/3';
      if (Math.abs(scaled - 0.67) < 0.05) return '2/3';
    }
    return scaled.toFixed(1).replace(/\.0$/, '');
  };

  const handleCopyShoppingList = () => {
    if (missingItems.length === 0) return;
    const textToCopy = missingItems
      .map((item) => `• ${formatScaledAmount(item.amount)} ${item.unit} ${item.name}`)
      .join('\n');
    
    const formatted = `Shopping list for "${recipe.title}":\n${textToCopy}\n\nGenerated by What Should I Cook?`;
    navigator.clipboard.writeText(formatted).then(() => {
      setCopiedShoppingList(true);
      setTimeout(() => setCopiedShoppingList(false), 2500);
    });
  };

  const handleCompleteRecipe = () => {
    onMarkCooked(recipe.id);
    confetti({
      particleCount: 80,
      spread: 60,
      origin: { y: 0.6 },
    });
  };

  const toggleStep = (index: number) => {
    setCheckedSteps((prev) =>
      prev.includes(index) ? prev.filter((i) => i !== index) : [...prev, index]
    );
  };

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-labelledby="modal-recipe-title"
      className="fixed inset-0 z-50 overflow-y-auto bg-stone-900/60 backdrop-blur-xs flex items-center justify-center p-3 sm:p-6 animate-in fade-in duration-200"
    >
      <div
        className="bg-white rounded-3xl max-w-2xl w-full max-h-[92vh] flex flex-col shadow-2xl border border-stone-200 overflow-hidden relative"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Sticky Header with Title and Close Button */}
        <div className="p-5 sm:p-6 border-b border-stone-100 flex items-start justify-between gap-4 sticky top-0 bg-white/95 backdrop-blur-xs z-10">
          <div>
            <div className="flex items-center gap-2 mb-1.5 flex-wrap">
              <span className="text-xs font-semibold px-2.5 py-0.5 rounded-full bg-stone-100 text-stone-700 capitalize">
                {recipe.mealType}
              </span>
              <span className="text-xs font-semibold px-2.5 py-0.5 rounded-full bg-emerald-50 text-emerald-800 capitalize">
                {recipe.difficulty}
              </span>
              {recipe.cuisine && (
                <span className="text-xs text-stone-500 font-medium">{recipe.cuisine}</span>
              )}
            </div>
            <h2 id="modal-recipe-title" className="text-xl sm:text-2xl font-bold tracking-tight text-stone-900">
              {recipe.title}
            </h2>
          </div>

          <div className="flex items-center gap-1.5">
            <button
              onClick={() => onToggleFavorite(recipe.id)}
              className={`p-2.5 rounded-full transition-colors ${
                isFavorite
                  ? 'bg-rose-50 text-rose-600'
                  : 'text-stone-400 hover:text-stone-700 hover:bg-stone-100'
              }`}
              title={isFavorite ? 'Remove from favorites' : 'Save to favorites'}
              aria-label={isFavorite ? 'Remove from favorites' : 'Save to favorites'}
            >
              <Heart className={`w-5 h-5 ${isFavorite ? 'fill-rose-500' : ''}`} />
            </button>

            <button
              onClick={onClose}
              className="p-2.5 rounded-full text-stone-400 hover:text-stone-700 hover:bg-stone-100 transition-colors"
              aria-label="Close recipe details"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Scrollable Body Content */}
        <div className="overflow-y-auto p-5 sm:p-7 space-y-7">
          <RecipeImage
            recipeId={recipe.id}
            alt={`${recipe.title}, plated and ready to serve`}
            className="aspect-[16/9] w-full rounded-2xl"
            sizes="(max-width: 768px) 100vw, 672px"
          />

          <p className="text-sm sm:text-base text-stone-600 leading-relaxed">
            {recipe.description}
          </p>

          {/* Quick Stats Grid */}
          <div className="grid grid-cols-3 gap-3 p-4 rounded-2xl bg-stone-50 border border-stone-100 text-center">
            <div>
              <span className="block text-xs text-stone-400 font-medium">Prep Time</span>
              <span className="text-sm sm:text-base font-bold text-stone-800">
                {recipe.prepTimeMinutes} min
              </span>
            </div>
            <div className="border-x border-stone-200/80">
              <span className="block text-xs text-stone-400 font-medium">Cook Time</span>
              <span className="text-sm sm:text-base font-bold text-stone-800">
                {recipe.cookTimeMinutes} min
              </span>
            </div>
            <div>
              <span className="block text-xs text-stone-400 font-medium">Total Duration</span>
              <span className="text-sm sm:text-base font-bold text-stone-800">
                {recipe.totalTimeMinutes} min
              </span>
            </div>
          </div>

          {/* Servings Adjuster */}
          <div className="flex items-center justify-between p-3.5 rounded-xl border border-stone-200/90 bg-white">
            <div className="flex items-center gap-2">
              <Users className="w-4 h-4 text-emerald-600" />
              <span className="text-xs sm:text-sm font-semibold text-stone-800">
                Adjust Servings
              </span>
            </div>
            <div className="flex items-center gap-3">
              <button
                type="button"
                onClick={() => setServings((prev) => Math.max(1, prev - 1))}
                className="w-8 h-8 rounded-lg border border-stone-200 flex items-center justify-center font-bold text-stone-600 hover:bg-stone-100 transition-colors"
                aria-label="Decrease servings"
              >
                -
              </button>
              <span className="font-bold text-stone-900 min-w-5 text-center text-sm sm:text-base">
                {servings}
              </span>
              <button
                type="button"
                onClick={() => setServings((prev) => Math.min(12, prev + 1))}
                className="w-8 h-8 rounded-lg border border-stone-200 flex items-center justify-center font-bold text-stone-600 hover:bg-stone-100 transition-colors"
                aria-label="Increase servings"
              >
                +
              </button>
            </div>
          </div>

          {/* Missing Ingredients Alert & Copyable Shopping List */}
          {missingItems.length > 0 && (
            <div className="p-4 rounded-2xl bg-amber-50/80 border border-amber-200/80">
              <div className="flex items-center justify-between gap-2 mb-2">
                <div className="flex items-center gap-1.5 text-xs font-bold text-amber-900">
                  <AlertCircle className="w-4 h-4 text-amber-700" />
                  <span>Missing {missingItems.length} Ingredients</span>
                </div>
                <button
                  type="button"
                  onClick={handleCopyShoppingList}
                  className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-lg bg-white border border-amber-300 text-amber-900 text-xs font-medium hover:bg-amber-100 transition-all shadow-2xs"
                >
                  {copiedShoppingList ? (
                    <>
                      <Check className="w-3.5 h-3.5 text-emerald-600" />
                      <span>Copied!</span>
                    </>
                  ) : (
                    <>
                      <Copy className="w-3.5 h-3.5" />
                      <span>Copy shopping list</span>
                    </>
                  )}
                </button>
              </div>

              <p className="text-xs text-amber-800 mb-2">
                You can still make this! Add these items to your grocery list:
              </p>
              <div className="flex flex-wrap gap-1.5">
                {missingItems.map((item) => (
                  <span
                    key={item.id}
                    className="text-xs bg-white/90 border border-amber-300 text-amber-950 px-2 py-0.5 rounded-md font-medium"
                  >
                    {formatScaledAmount(item.amount)} {item.unit} {item.name}
                  </span>
                ))}
              </div>
            </div>
          )}

          {/* Complete Ingredients List */}
          <div>
            <h3 className="text-base sm:text-lg font-bold text-stone-900 mb-3">
              Ingredients
            </h3>
            <ul className="divide-y divide-stone-100 border-t border-b border-stone-100">
              {recipe.ingredients.map((ing) => {
                const isHave = isIngredientMatched(ing.normalizedName, userNormalizedList);
                return (
                  <li
                    key={ing.id}
                    className="py-2.5 flex items-center justify-between text-xs sm:text-sm"
                  >
                    <div className="flex items-center gap-2.5">
                      <span
                        className={`w-4 h-4 rounded-full flex items-center justify-center shrink-0 ${
                          isHave
                            ? 'bg-emerald-100 text-emerald-700'
                            : 'bg-stone-100 text-stone-400'
                        }`}
                      >
                        {isHave ? <Check className="w-2.5 h-2.5" /> : '•'}
                      </span>
                      <span
                        className={`${
                          isHave ? 'text-stone-900 font-medium' : 'text-stone-700'
                        }`}
                      >
                        {ing.name}
                        {ing.optional && (
                          <span className="text-stone-400 ml-1 font-normal text-xs">(optional)</span>
                        )}
                      </span>
                    </div>

                    <span className="text-stone-500 font-medium shrink-0 ml-4">
                      {formatScaledAmount(ing.amount)} {ing.unit}
                    </span>
                  </li>
                );
              })}
            </ul>
          </div>

          {/* Step-by-Step Cooking Instructions */}
          <div>
            <h3 className="text-base sm:text-lg font-bold text-stone-900 mb-3">
              Cooking Instructions
            </h3>
            <div className="space-y-3">
              {recipe.instructions.map((step, idx) => {
                const isChecked = checkedSteps.includes(idx);
                return (
                  <div
                    key={idx}
                    onClick={() => toggleStep(idx)}
                    className={`cursor-pointer p-3.5 rounded-xl border transition-all flex items-start gap-3 ${
                      isChecked
                        ? 'bg-stone-50 border-stone-200 text-stone-400 line-through'
                        : 'bg-white border-stone-200/90 hover:border-emerald-500/50 text-stone-800'
                    }`}
                  >
                    <span
                      className={`w-6 h-6 rounded-full flex items-center justify-center text-xs font-bold shrink-0 mt-0.5 ${
                        isChecked
                          ? 'bg-stone-200 text-stone-500'
                          : 'bg-emerald-600 text-white'
                      }`}
                    >
                      {idx + 1}
                    </span>
                    <p className="text-xs sm:text-sm leading-relaxed">{step}</p>
                  </div>
                );
              })}
            </div>
          </div>
        </div>

        {/* Footer Actions */}
        <div className="p-4 sm:p-5 border-t border-stone-100 bg-stone-50 flex items-center justify-between gap-3 sticky bottom-0">
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-2.5 rounded-xl border border-stone-200 text-stone-700 hover:bg-stone-100 font-medium text-xs sm:text-sm transition-colors"
          >
            Close
          </button>

          <button
            type="button"
            onClick={handleCompleteRecipe}
            className={`px-5 py-2.5 rounded-xl font-medium text-xs sm:text-sm flex items-center gap-2 transition-all ${
              isCooked
                ? 'bg-emerald-700 text-white shadow-xs'
                : 'bg-stone-900 hover:bg-stone-800 text-white shadow-xs'
            }`}
          >
            {isCooked ? (
              <>
                <PartyPopper className="w-4 h-4" />
                <span>Cooked it! Great job!</span>
              </>
            ) : (
              <>
                <CheckCircle className="w-4 h-4" />
                <span>Mark as “Cooked It”</span>
              </>
            )}
          </button>
        </div>
      </div>
    </div>
  );
};
